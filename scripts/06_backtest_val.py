"""Stage 2 report: model scores and a betting backtest on out-of-sample 2019-2024 predictions.

Reads data/oof_predictions.csv (written by 05_train.py) and the tuning tables.
Writes reports/stage2_validation.md and data/val_ledger.csv. Uses no test-period data.
"""
import json
import sys

import _path  # noqa: F401
import numpy as np
import pandas as pd

from ufc import ROOT, load_config
from ufc.backtest import ledger, summarise
from ufc.market import sigmoid
from ufc.metrics import accuracy, brier, calibration_table, event_bootstrap, log_loss

cfg = load_config()
data, reports = ROOT / cfg["paths"]["data"], ROOT / cfg["paths"]["reports"]
o = pd.read_csv(data / "oof_predictions.csv", parse_dates=["date"])
assert o.date.max() < pd.Timestamp(cfg["splits"]["test_start"])
best = json.load(open(data / "stage2_best_params.json", encoding="utf-8"))
REPS, SEED = cfg["bootstrap"]["reps"], cfg["seed"]

# choices fixed here after looking only at 2019-2024 out-of-sample results
PRIMARY = sys.argv[1] if len(sys.argv) > 1 else "Bens"
THRESHOLD = float(sys.argv[2]) if len(sys.argv) > 2 else 0.05
CAP = float(sys.argv[3]) if len(sys.argv) > 3 else 0.20

L = []


def table(df, nd=4):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{nd}f}")
    L.extend(["| " + " | ".join(map(str, df.columns)) + " |", "|" + "|".join("---" for _ in df.columns) + "|",
              *["| " + " | ".join(map(str, r)) + " |" for r in df.values], ""])


def h(text, level=2):
    L.extend(["#" * level + " " + text, ""])


def logit(p):
    return np.log(p / (1 - p))


o["z_open"], o["z_close"], o["z_elo"] = logit(o.p_open), logit(o.p_close), logit(o.p_elo.clip(1e-6, 1 - 1e-6))
C = o[o.is_target & o.market_ok].reset_index(drop=True)      # common scoring set
NAMES = {"elo": "Elo only", "A1": "A1 logistic, no odds", "A2": "A2 boosting, no odds",
         "Aens": "A average", "open": "Opening odds", "stretch": "Stretched opening odds",
         "B1": "B1 logistic + opening odds", "B2": "B2 boosting + opening odds", "Bens": "B average",
         "close": "Closing odds", "close_plus": "(check) features + closing odds"}

L.append("# Stage 2 report: training and validation\n")
L.append("Generated by `scripts/06_backtest_val.py`. Every number is out-of-sample: each year from 2019 to "
         "2024 was predicted by models trained only on earlier fights. The 2025-26 test period was not "
         "read by any training or tuning code.\n")

# ------------------------------------------------------------------ 1 scores
h("1. Model scores, 2019-2024 out-of-sample")
L.append(f"{len(C)} decided fights with usable opening and closing odds; identical for every row. "
         "Lower log loss is better.\n")


def delta(col, ref):
    y, a, b = C.y.values, sigmoid(C["z_" + col].values), sigmoid(C["z_" + ref].values)
    d = log_loss(y, a) - log_loss(y, b)
    lo, hi = event_bootstrap(C.date.values, lambda i: log_loss(y[i], a[i]) - log_loss(y[i], b[i]), REPS, SEED)
    return d, lo, hi


rows = []
for k, nm in NAMES.items():
    p = sigmoid(C["z_" + k].values)
    d, lo, hi = delta(k, "open")
    rows.append({"model": nm, "accuracy": accuracy(C.y, p), "log_loss": log_loss(C.y, p), "brier": brier(C.y, p),
                 "vs_opening": d, "low": lo, "high": hi})
scores = pd.DataFrame(rows)
table(scores)
L.append("`vs_opening` is the log-loss difference from the opening odds with a 95% interval from resampling "
         "event nights. Negative is better than the opening odds; an interval entirely below zero is a "
         "clear win.\n")

h("Against the stretched opening odds", 3)
rows = []
for k in ("B1", "B2", "Bens"):
    d, lo, hi = delta(k, "stretch")
    rows.append({"model": NAMES[k], "vs_stretched": d, "low": lo, "high": hi})
table(pd.DataFrame(rows))

h("Year by year: log loss minus the opening odds", 3)
rows = []
for yr, g in C.groupby(C.date.dt.year):
    r = {"year": yr, "fights": len(g)}
    for k in ("Aens", "stretch", "B1", "B2", "Bens", "close"):
        r[NAMES[k]] = log_loss(g.y, sigmoid(g["z_" + k])) - log_loss(g.y, g.p_open)
    rows.append(r)
table(pd.DataFrame(rows))

h("Leak check: do the fight features improve on the closing odds?", 3)
d, lo, hi = delta("close_plus", "close")
L.append(f"The B1 recipe placed on top of the closing odds changes log loss by {d:+.4f} "
         f"(95% interval {lo:+.4f} to {hi:+.4f}). The closing line is the sharpest price there is, so a "
         "large improvement here would point to a leak. A small one is consistent with real, modest "
         "information in the features.\n")

# ------------------------------------------------------------------ 2 chosen settings
h("2. Chosen settings")
for k in ("A1", "A2", "B1", "B2"):
    b = {kk: vv for kk, vv in best[k].items() if kk not in ("kind", "market")}
    L.append(f"- **{k}:** `{json.dumps(b)}`")
tl, tg = pd.read_csv(data / "tuning_logit.csv"), pd.read_csv(data / "tuning_gbm.csv")
L.append(f"- Candidates tried: {len(tl)} logistic settings and {tg.drop(columns=['rounds', 'log_loss']).drop_duplicates().shape[0]} "
         f"boosting settings (each at {tg.rounds.nunique()} tree counts).")
for market, nm in ((False, "A"), (True, "B")):
    a, b = tl[tl.market == market].log_loss, tg[tg.market == market].log_loss
    L.append(f"- {nm} models: logistic log loss ranged {a.min():.4f} to {a.max():.4f} across settings "
             f"(top 10 within {a.nsmallest(10).max() - a.min():.4f}); boosting {b.min():.4f} to {b.max():.4f}.")
L.append("")
h("Calibration", 3)
rows = []
for k in ("A1", "A2", "Aens", "B1", "B2", "Bens"):
    s = best["calibration_slopes"][k]
    late = C[C.date.dt.year >= 2020]
    rows.append({"model": NAMES[k], "slope_fitted_before_2024": s["2024"],
                 "log_loss_2020_24_raw": log_loss(late.y, sigmoid(late["z_" + k])),
                 "log_loss_2020_24_rescaled": log_loss(late.y, sigmoid(late["z_" + k + "_cal"]))})
table(pd.DataFrame(rows))
L.append("A slope near 1 means the probabilities need no correction. `rescaled` applies a slope fitted "
         "only on earlier years.\n")
h(f"Calibration of {NAMES[PRIMARY]}", 3)
table(calibration_table(C.y, sigmoid(C["z_" + PRIMARY])).astype({"band": str}), 3)

h("What the logistic model adds to the opening odds", 3)
coef = pd.read_csv(data / "b1_coefficients.csv")
L.append(f"Weight on the opening odds: {best['B1']['market_slope_full_fit']:.3f} (1.0 would mean taking the "
         "odds at face value). Largest adjustments, per standard deviation of each feature; positive "
         "favours the fighter with the higher value:\n")
table(coef.head(12), 3)

# ------------------------------------------------------------------ 3 betting
h("3. Betting backtest at opening prices, 2019-2024 out-of-sample")
M = o[o.market_ok].reset_index(drop=True)          # includes draws and no contests, settled as void
L.append(f"One unit per bet on the side where `model probability x price - 1` exceeds the threshold. "
         f"{len(M)} fights with usable odds, of which {int((~M.is_target).sum())} were draws or no contests "
         "(stake returned).\n")
h("Threshold grid", 3)
rows = []
for k in ("stretch", "Aens", "B1", "B2", "Bens"):
    for thr in (0.0, 0.02, 0.05, 0.08, 0.10):
        s = summarise(ledger(M, M["z_" + k], thr, CAP), REPS, SEED)
        rows.append({"model": NAMES[k], "threshold": thr, "bets": s["bets"], "return": s.get("return"),
                     "low": s.get("return_low"), "high": s.get("return_high"), "clv": s.get("clv"),
                     "clv_low": s.get("clv_low"), "clv_high": s.get("clv_high")})
grid = pd.DataFrame(rows)
table(grid, 3)
L.append(f"`return` is profit per unit staked, with a 95% interval. `clv` is the value of the price taken "
         f"measured against the closing line with the margin removed; above zero means the bets beat the "
         f"close. Edges above {CAP:.0%} are skipped as likely model error. The stretched-odds row is the "
         "no-knowledge strategy: any real model has to beat it.\n")

prim = ledger(M, M["z_" + PRIMARY], THRESHOLD, CAP)
prim.to_csv(data / "val_ledger.csv", index=False, date_format="%Y-%m-%d")
s = summarise(prim, REPS, SEED)
h(f"Chosen rule: {NAMES[PRIMARY]}, threshold {THRESHOLD:.0%}, cap {CAP:.0%}", 3)
L.append(f"- Bets: {s['bets']} over six years ({s['bets'] / 6:.0f} a year), {s['win_rate']:.1%} won, "
         f"average price {s['avg_price']:.2f}.")
L.append(f"- Return: {s['return']:+.1%} per unit staked (95% interval {s['return_low']:+.1%} to "
         f"{s['return_high']:+.1%}); {s['units_won']:+.1f} units in total.")
L.append(f"- Closing-line value: {s['clv']:+.1%} (95% interval {s['clv_low']:+.1%} to {s['clv_high']:+.1%}); "
         f"{s['beat_close_share']:.0%} of bets beat the close.")
L.append(f"- Worst peak-to-trough run: {s['max_drawdown']:.1f} units.\n")

h("Honesty checks on the chosen rule", 3)
rows = []


def add(label, led):
    s = summarise(led, REPS, SEED)
    rows.append({"check": label, "bets": s["bets"], "return": s.get("return"), "low": s.get("return_low"),
                 "high": s.get("return_high"), "clv": s.get("clv")})


add("As chosen", prim)
for hc in (0.02, 0.05):
    add(f"Prices {hc:.0%} worse than recorded", ledger(M, M["z_" + PRIMARY], THRESHOLD, CAP, h=hc))
add("Bet at the CLOSING price instead (lower bound)", ledger(M, M["z_" + PRIMARY], THRESHOLD, CAP, price="close"))
add("Without the 5% of bets with the largest line moves", prim[prim.move <= prim.move.quantile(0.95)])
add("Without the 10% of bets with the largest line moves", prim[prim.move <= prim.move.quantile(0.90)])
H = o[o.has_market].reset_index(drop=True)
add("Including the fights with conflicting odds", ledger(H, H["z_" + PRIMARY], THRESHOLD, CAP))
add("No cap on the edge", ledger(M, M["z_" + PRIMARY], THRESHOLD))
add("Favourites only", prim[prim.is_favourite])
add("Underdogs only", prim[~prim.is_favourite])
for yr, g in prim.groupby(prim.date.dt.year):
    add(f"Year {yr}", g)
table(pd.DataFrame(rows), 3)

(reports / "stage2_validation.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
