"""Step 4: market and Elo baselines plus the Stage 1 trust checks.

Reads data/features.csv, data/fighter_prefight.csv, data/fights_clean.csv.
Writes reports/stage1_baselines.md. No model is trained here: the only fitted
number is the one-parameter stretch of the opening odds, fitted on 2013-2022.
"""
import _path  # noqa: F401
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from ufc import ROOT, load_config
from ufc.clean import load_clean
from ufc.features import BASE, FEATURES, STATIC
from ufc.market import fit_stretch, flat_return, stretch
from ufc.metrics import calibration_table, event_bootstrap, log_loss, summary

cfg = load_config()
data, reports = ROOT / cfg["paths"]["data"], ROOT / cfg["paths"]["reports"]
f = pd.read_csv(data / "features.csv", parse_dates=["date"])
pre = pd.read_csv(data / "fighter_prefight.csv", parse_dates=["date"])
clean = load_clean(cfg)
L = []          # report lines


def table(df, floatfmt=4):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{floatfmt}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.values]
    L.extend([head, sep, *rows, ""])


def h(text, level=2):
    L.extend(["#" * level + " " + text, ""])


L.append("# Stage 1 report: data, features and baselines\n")
L.append("Generated by `scripts/04_baselines.py`. No model has been trained.\n")

# ------------------------------------------------------------------ 1 row accounting
h("1. Row accounting")
acc = (f.assign(decided=f.is_target, market=f.has_market & f.is_target,
                market_clean=f.market_ok & f.is_target)
        .groupby("split").agg(fights=("y", "size"), decided=("decided", "sum"),
                              with_open_and_close=("market", "sum"),
                              usable_for_market_scoring=("market_clean", "sum"))
        .loc[["history", "train", "val", "test", "after_test"]].reset_index())
table(acc)
L.append(f"- Total fights: {len(f)}. Decided (prediction targets): {int(f.is_target.sum())}. "
         f"Draws: {int((f.result == 'draw').sum())}. No contests: {int((f.result == 'no contest').sum())}.")
L.append("- `history` = before 2010: used for fighter histories and Elo, not as training rows.")
L.append("- `after_test` = the last four cards (after 2026-10-10), which have no odds.")
L.append("- The same-night rematch Sakuraba vs Silveira (1997-12-21) is kept as two fights.")
sus = clean[clean.open_suspect]
L.append(f"- `usable_for_market_scoring` drops {int((f.has_market & f.odds_conflict).sum())} fights where odds "
         f"sources disagree and {len(sus)} where the opening line is a mirror image of the close "
         f"({'; '.join(f'{a} vs {b}, {d:%Y-%m-%d}' for a, b, d in zip(sus.fighter_1, sus.fighter_2, sus.date))}).")
L.append("- Results are as settled on fight night. One test fight (Osbourne vs Idiris, 2026-02-21) is a "
         "win here and an overturned no contest in the other source; it is kept as a win.\n")

# ------------------------------------------------------------------ 2 identity
h("2. Fighter identity")
keys = pd.concat([clean[["fighter_1", "f1_key"]].set_axis(["name", "key"], axis=1),
                  clean[["fighter_2", "f2_key"]].set_axis(["name", "key"], axis=1)]).drop_duplicates()
multi = keys.groupby("name").key.nunique()
L.append(f"- Fighters: {keys.key.nunique()} identities from {keys.name.nunique()} distinct names.")
L.append(f"- Names shared by more than one fighter: {multi[multi > 1].to_dict()}.")
alias = keys.groupby("key").name.agg(lambda s: sorted(set(s)))
alias = alias[alias.map(len) > 1]
L.append(f"- Fighters appearing under more than one spelling: {len(alias)} "
         f"({'; '.join(' = '.join(a) for a in alias.head(6))}).")
by_id = (keys.key.str.startswith("n:")).groupby(keys.key).first()
L.append(f"- Identified by ufcstats fighter ID: {int((~by_id).sum())}. By name only "
         f"(careers that ended before 2013): {int(by_id.sum())}.\n")
gap = pre.sort_values(["fighter", "date"]).copy()
gap["prev"] = gap.groupby("fighter").date.shift()
gap["layoff_years"] = (gap.date - gap.prev).dt.days / 365.25
top = gap.nlargest(10, "layoff_years")[["name", "prev", "date", "layoff_years"]]
top["prev"], top["date"] = top.prev.dt.date, top.date.dt.date
L.append("Ten longest gaps between UFC fights (a wrong merge of two people would show up here):\n")
table(top.rename(columns={"prev": "previous fight", "date": "next fight"}), 1)

# ------------------------------------------------------------------ 3 order neutrality
h("3. Fighter order is neutral")
t = f[f.is_target]
era = pd.cut(t.date.dt.year, [1992, 2009, 2014, 2018, 2022, 2024, 2026],
             labels=["1993-2009", "2010-14", "2015-18", "2019-22", "2023-24", "2025-26"])
o = t.groupby(era, observed=True).agg(fights=("y", "size"), fighter_A_win_rate=("y", "mean")).reset_index()
o["standard_errors_from_50pct"] = (o.fighter_A_win_rate - 0.5) / (0.5 / np.sqrt(o.fights))
table(o.rename(columns={"date": "period"}), 3)
L.append("In the source file the first-listed fighter won 100% of fights before 2010. The order is now "
         "set by a fixed pseudo-random coin flip per fight that cannot see the result.")
worst = o.loc[o.standard_errors_from_50pct.abs().idxmax()]
L.append(f"- Largest imbalance: {worst.date} at {worst.fighter_A_win_rate:.1%}, "
         f"{abs(worst.standard_errors_from_50pct):.1f} standard errors from 50%. This is chance in the coin "
         "flips, not information: every model in the plan is symmetric in the two fighters, so its "
         "predictions and scores are identical whichever fighter is called A.\n")

# ------------------------------------------------------------------ 4 missingness audit
h("4. Missing-value audit")
p1 = pre[pre.side == 1].set_index("fight_id").loc[clean.fight_id]
p2 = pre[pre.side == 2].set_index("fight_id").loc[clean.fight_id]
rows = []
for col in STATIC:
    for label, lo, hi in (("before 2010", "1993", "2009"), ("2010-22", "2010", "2022"), ("2023-26", "2023", "2026")):
        m = ((clean.date >= lo + "-01-01") & (clean.date <= hi + "-12-31") & clean.is_target).values
        only1 = m & p1[col].isna().values & p2[col].notna().values
        only2 = m & p2[col].isna().values & p1[col].notna().values
        n = only1.sum() + only2.sum()
        wins = (clean.f1_won.values[only1] == 1).sum() + (clean.f1_won.values[only2] == 0).sum()
        rows.append({"attribute": col, "period": label, "fights_one_side_missing": int(n),
                     "missing_side_win_rate": wins / n if n else np.nan})
table(pd.DataFrame(rows), 3)
L.append("A fighter whose profile lacks an attribute lost far more often than not before 2023, "
         "because profiles of fighters who left early were never completed. That is why a missing "
         "attribute gives a difference of exactly 0 and there is no missing-value flag.\n")
L.append(f"- Missing values left in the feature table: {int(f[FEATURES].isna().sum().sum())}.\n")

# ------------------------------------------------------------------ 5 hand checks
h("5. Spot checks: what the table knew before well-known fights")
checks = [("Khabib Nurmagomedov", "Conor McGregor", "2018-10-06"), ("Jon Jones", "Daniel Cormier", "2015-01-03"),
          ("Amanda Nunes", "Ronda Rousey", "2016-12-30"), ("Israel Adesanya", "Alex Pereira", "2022-11-12"),
          ("Islam Makhachev", "Charles Oliveira", "2022-10-22")]
rows = []
for a, b, d in checks:
    for nm in (a, b):
        r = pre[(pre.name == nm) & (pre.date == d)]
        if len(r) != 1:
            rows.append({"fighter": nm, "fight date": d, "note": "not found"})
            continue
        r = r.iloc[0]
        rows.append({"fighter": nm, "fight date": d,
                     "UFC record": f"{int(r.raw_wins)}-{int(r.raw_losses)}", "fights": int(r.n_fights),
                     "days since last": r.days_since, "age": r.age, "reach cm": r.reach_cm,
                     "sig. strikes/min": r.c_slpm, "absorbed/min": r.c_sapm,
                     "takedowns/15": r.c_td_p15, "Elo": r.elo})
table(pd.DataFrame(rows), 2)
L.append("Records are UFC-only and count fights strictly before the date shown.\n")

# ------------------------------------------------------------------ 6 Elo sanity
h("6. Elo sanity")
peak = pre.loc[pre.groupby("fighter").elo.idxmax(), ["name", "elo", "date"]].nlargest(15, "elo")
peak["date"] = peak.date.dt.date
table(peak.rename(columns={"elo": "peak pre-fight Elo", "date": "on"}), 0)

# ------------------------------------------------------------------ 7 baselines
h("7. Baselines")
m = f[f.is_target & f.market_ok].copy()
tr = m[m.split == "train"]
s = fit_stretch(tr.p_open, tr.y)
m["p_stretch"] = stretch(m.p_open, s)
L.append("Scored on decided fights usable for market scoring (see section 1). "
         "All baselines in a block are scored on identical fights. Accuracy counts an exact 50/50 "
         "prediction as half a correct pick; Elo has many of these (two debutants), the odds have few.\n")
L.append(f"**Stretch factor fitted on 2013-2022: {s:.3f}.** Above 1 means opening favourites win "
         f"more often than their price says.\n")
names = {"p_elo": "Elo only", "p_open": "Opening odds", "p_stretch": "Stretched opening odds",
         "p_close": "Closing odds"}
periods = {"Train 2013-22": "train", "Validation 2023-24": "val", "Test 2025-26": "test"}
rows = []
for label, sp in periods.items():
    g = m[m.split == sp]
    for col, nm in names.items():
        r = summary(g.y, g[col])
        lo, hi = event_bootstrap(g.date.values, lambda i, c=col, g=g: log_loss(g.y.values[i], g[c].values[i]),
                                 cfg["bootstrap"]["reps"], cfg["seed"])
        rows.append({"period": label, "baseline": nm, "fights": r["n"], "accuracy": r["accuracy"],
                     "log_loss": r["log_loss"], "log_loss_95_low": lo, "log_loss_95_high": hi,
                     "brier": r["brier"]})
base = pd.DataFrame(rows)
table(base)

h("Does the stretch beat the raw opening odds?", 3)
rows = []
for label, sp in periods.items():
    g = m[m.split == sp]
    y, a, b = g.y.values, g.p_stretch.values, g.p_open.values
    diff = log_loss(y, a) - log_loss(y, b)
    lo, hi = event_bootstrap(g.date.values, lambda i: log_loss(y[i], a[i]) - log_loss(y[i], b[i]),
                             cfg["bootstrap"]["reps"], cfg["seed"])
    rows.append({"period": label, "log_loss_change": diff, "95_low": lo, "95_high": hi})
table(pd.DataFrame(rows))
L.append("Negative means the stretched odds are better. The train row is in-sample by construction.\n")

h("Blind betting at the opening price", 3)
rows = []
for label, sp in periods.items():
    g = m[(m.split == sp) & (m.p_open != 0.5)]
    fav_a = (g.p_open > 0.5).values
    rows.append({"period": label, "fights": len(g),
                 "favourite_return": flat_return(g.y.values, g.a_open_decimal.values, g.b_open_decimal.values, fav_a),
                 "underdog_return": flat_return(g.y.values, g.a_open_decimal.values, g.b_open_decimal.values, ~fav_a)})
table(pd.DataFrame(rows), 3)
L.append("Return per unit staked, even-money fights left out. Underdogs lost clearly more than "
         "favourites in 2013-24; in the test period the two are about the same.\n")

h("Calibration of the opening odds (validation, 2023-24)", 3)
g = m[m.split == "val"]
table(calibration_table(g.y, g.p_open).astype({"band": str}), 3)
h("Calibration of the stretched opening odds (validation, 2023-24)", 3)
table(calibration_table(g.y, g.p_stretch).astype({"band": str}), 3)

over = 1 / m.a_open_decimal + 1 / m.b_open_decimal - 1
L.append(f"- Bookmaker margin in the opening odds: median {over.median():.1%} "
         f"(5th to 95th percentile {over.quantile(.05):.1%} to {over.quantile(.95):.1%}).")
move = (m.p_close - m.p_open).abs()
L.append(f"- Average move from open to close: {move.mean():.3f} in probability; the favourite "
         f"changes sides in {(((m.p_open > .5) & (m.p_close < .5)) | ((m.p_open < .5) & (m.p_close > .5))).mean():.1%} of fights.\n")

# ------------------------------------------------------------------ 8 single-feature strength
h("8. How well each single feature orders winners (train, fights with odds)")
mk = f[f.is_target & f.market_ok & (f.split == "train")]
auc = pd.Series({c: roc_auc_score(mk.y, mk[c]) for c in FEATURES})
auc = (auc - 0.5).abs().add(0.5).sort_values(ascending=False)
table(auc.head(12).rename("auc").rename_axis("feature").reset_index(), 3)
L.append(f"On the same {len(mk)} fights the opening odds score {roc_auc_score(mk.y, mk.p_open):.3f} and the "
         f"closing odds {roc_auc_score(mk.y, mk.p_close):.3f} (0.5 is a coin flip). This table shows feature "
         "strength only. It is not a leak test: a leak confined to a few hundred rows would not show here. "
         "The leak tests are the truncation, mutation and missing-value tests in `tests/`.\n")

h("Missing reach is no longer recognisable", 3)
c2 = clean.set_index("fight_id").loc[f.fight_id]
still = (c2.f1_reach_cm.isna() ^ c2.f2_reach_cm.isna()).values
raw = pd.read_csv(ROOT / cfg["paths"]["enriched"], usecols=["fight_url", "f1_reach_cm", "f2_reach_cm"])
raw["fight_id"] = raw.fight_url.str.extract(r"fight-details/(\w+)")[0]
raw = raw.dropna(subset=["fight_id"]).set_index("fight_id").reindex(f.fight_id)
raw_one = (raw.f1_reach_cm.isna() ^ raw.f2_reach_cm.isna()).values
rows = []
for sp in ("train", "val", "test"):
    s_ = (f.split == sp).values & f.is_target.values
    rows.append({"period": sp, "fights_one_reach_missing_in_source": int((raw_one & s_).sum()),
                 "reach_difference_exactly_zero": int((raw_one & s_ & (f.d_reach_cm.values == 0)).sum())})
table(pd.DataFrame(rows))
L.append("A missing reach is filled from the same fighter's other fights or estimated from height. The "
         "difference stays at 0 only when height is missing too, which is the brand-new fighter whose "
         "profile is not yet in the source.\n")

# ------------------------------------------------------------------ 9 distributions
h("9. Feature ranges by period")
rows = []
for c in ["d_" + b for b in BASE]:
    r = {"feature": c}
    for sp in ("train", "val", "test"):
        v = f.loc[f.split == sp, c]
        r[f"{sp}_sd"] = v.std()
        r[f"{sp}_zero_share"] = (v == 0).mean()
    r["min"], r["max"] = f.loc[f.split != "history", c].min(), f.loc[f.split != "history", c].max()
    rows.append(r)
table(pd.DataFrame(rows), 3)

(reports / "stage1_baselines.md").write_text("\n".join(L), encoding="utf-8")
print("wrote", reports / "stage1_baselines.md")
print(base.to_string())
print("stretch", round(s, 4))
